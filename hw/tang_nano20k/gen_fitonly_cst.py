"""
Generate tang_nano20k_fitonly.cst: assigns every top-level pin of
top_tang_nano20k to a plain I/O pin of the GW2AR-18C QFN88 package so that
nextpnr (which rejects unconstrained I/O) can measure fit and Fmax before the
real wiring is decided ([SPEC-TN20K-02], [SPEC-TN20K-03]).

These assignments are arbitrary. NEVER wire hardware to a fit-only bitstream.

Run with the oss-cad-suite Python (it ships apycula):
  ~/.tools/oss-cad-suite/py3bin/python3 hw/tang_nano20k/gen_fitonly_cst.py
"""
# @impl [SPEC-TN20K-03] hw/tang_nano20k/SPECIFICATION.md

import glob
from pathlib import Path

from apycula import chipdb

HERE = Path(__file__).resolve().parent
CLOCK_PIN = "4"  # same as tang_nano20k.cst (27 MHz oscillator, LPLL1_T_IN)

PORTS = (["i_reset_n", "i_spi_sclk", "i_spi_cs_n", "io_spi_io0", "io_spi_io1", "o_int_req",
          "o_imu_sclk", "o_imu_cs_n", "o_imu_mosi", "i_imu_miso", "i_imu_int", "o_neopixel_pin"]
         + [f"o_motor_pins[{i}]" for i in range(4)]
         + [f"i_pwm_pins[{i}]" for i in range(6)]
         + [f"o_led[{i}]" for i in range(6)])


def plain_pins():
    """QFN88 pins with no special function (no JTAG, config, PLL or global clock)."""
    import apycula
    db = chipdb.load_chipdb(str(Path(apycula.__file__).parent / "GW2A-18C.msgpack.xz"))
    pins = db.pinout["GW2AR-18C"]["QFN88"]
    plain = [p for p, (_, funcs) in pins.items() if not funcs and p != CLOCK_PIN]
    return sorted(plain, key=int)


def main():
    pins = plain_pins()
    assert len(pins) >= len(PORTS), f"{len(pins)} plain pins < {len(PORTS)} ports"
    out = ["// GENERATED by gen_fitonly_cst.py -- FIT/TIMING MEASUREMENT ONLY.",
           "// Pins are arbitrary plain I/O of the GW2AR-18C QFN88 package.",
           "// NEVER wire hardware to a bitstream built from this file.",
           "",
           f'IO_LOC "i_clk" {CLOCK_PIN};',
           'IO_PORT "i_clk" IO_TYPE=LVCMOS33 PULL_MODE=UP;']
    for port, pin in zip(PORTS, pins):
        out.append(f'IO_LOC "{port}" {pin};')
        out.append(f'IO_PORT "{port}" IO_TYPE=LVCMOS33;')
    (HERE / "tang_nano20k_fitonly.cst").write_text("\n".join(out) + "\n")
    print(f"assigned {len(PORTS)} ports + clock to {len(PORTS)} of {len(pins)} plain pins")


if __name__ == "__main__":
    main()
